import { chromium, devices } from '@playwright/test';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome' });
const ctx = await b.newContext(devices['iPhone 13']);
const p = await ctx.newPage();
await p.goto('http://localhost:4173/#/conjugation');
await p.getByRole('button', { name: /添加 \d+ 个核心动词/ }).click({ timeout: 30000 });
await p.waitForTimeout(2500);
await p.reload();
await p.getByLabel('变位答案').waitFor({ timeout: 30000 });
await p.screenshot({ path: '/tmp/conj-q.png' });
await p.getByLabel('变位答案').fill('je prendu');
await p.getByRole('button', { name: '检查' }).click();
await p.waitForTimeout(300);
await p.screenshot({ path: '/tmp/conj-a.png', fullPage: false });
await p.goto('http://localhost:4173/#/conjugation?v=venir');
await p.waitForTimeout(1500);
await p.getByText('p.p. venu').scrollIntoViewIfNeeded();
await p.screenshot({ path: '/tmp/conj-l.png' });
await b.close();
