import { chromium } from '@playwright/test';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome' });
const p = await b.newPage({ viewport: { width: 1000, height: 800 } });
p.on('pageerror', (e) => console.log('PAGEERROR', e.message));
p.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE', m.text()); });
await p.goto('http://localhost:4173/#/data');
await p.getByLabel('粘贴 JSON').fill(JSON.stringify({ vocab: [{ lemma: 'apprenant', article: 'l’', gender: 'm', pos: 'noun', plural: 'apprenants', ipa: 'a.pʁə.nɑ̃', defEn: 'learner', defZh: '学习者', examples: [{ fr: 'Ce cours s’adresse aux jeunes apprenants.' }] }] }));
await p.getByRole('button', { name: '校验并预览' }).click();
await p.getByRole('button', { name: '确认导入' }).click();
await p.getByRole('status').first().waitFor();
console.log('TOAST', await p.getByRole('status').first().innerText());
await p.goto('http://localhost:4173/#/review');
await p.waitForTimeout(800);
console.log('MAIN', JSON.stringify(await p.locator('main').innerText()));
await p.getByRole('button', { name: '显示答案' }).click();
await p.mouse.move(0, 0);
await p.waitForTimeout(300);
await p.screenshot({ path: '/tmp/review-fixed.png' });
await b.close();
